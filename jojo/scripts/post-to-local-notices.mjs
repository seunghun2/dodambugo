async function postNoticesToLocal() {
  console.log('로컬 API(http://localhost:3000/api/b2b/admin/notices)에 공지 5건 POST 전송 시작...');

  for (const notice of officialNotices) {
    try {
      const res = await fetch('http://localhost:3000/api/b2b/admin/notices', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(notice)
      });
      const data = await res.json();
      if (res.ok && data.success) {
        console.log(`✓ 로컬 공지 등록 성공: ${notice.title}`);
      } else {
        console.error(`✕ 로컬 공지 등록 실패 (${notice.title}):`, data);
      }
    } catch (err) {
      console.error(`✕ 네트워크 오류 (${notice.title}):`, err);
    }
  }
}

postNoticesToLocal();
